function addPageHeaderAndFooter(
  doc: jsPDF,
  title: string,
  sessionId: string
) {
  const pageCount = doc.getNumberOfPages();
  for (let page = 1; page <= pageCount; page++) {
    doc.setPage(page);

    // Skip header band on the first page (title band already there)
    if (page > 1) {
      // Header band
      doc.setFillColor(BRAND_PRIMARY[0], BRAND_PRIMARY[1], BRAND_PRIMARY[2]);
      doc.rect(0, 0, PAGE_WIDTH, 12, "F");

      doc.setFont("helvetica", "bold");
      doc.setFontSize(9);
      doc.setTextColor(WHITE[0], WHITE[1], WHITE[2]);
      doc.text(title, MARGIN, 8);

      doc.setFont("helvetica", "normal");
      doc.setFontSize(8);
      doc.text(sessionId, PAGE_WIDTH - MARGIN, 8, { align: "right" });
    }

    // Footer
    doc.setFont("helvetica", "normal");
    doc.setFontSize(8);
    doc.setTextColor(120, 120, 120);
    doc.text(
      `Page ${page} of ${pageCount}`,
      PAGE_WIDTH / 2,
      PAGE_HEIGHT - 8,
      { align: "center" }
    );
    doc.text(
      "Generated by Text Inspection",
      MARGIN,
      PAGE_HEIGHT - 8
    );
  }
}

function addSectionTitle(doc: jsPDF, text: string) {
  doc.setFont("helvetica", "bold");
  doc.setFontSize(13);
  doc.setTextColor(BRAND_PRIMARY[0], BRAND_PRIMARY[1], BRAND_PRIMARY[2]);
  doc.text(text, MARGIN, getY(doc) + 6);
  setY(doc, getY(doc) + 10);
}

function getY(doc: jsPDF): number {
  return (doc as unknown as { y: number }).y;
}

function setY(doc: jsPDF, y: number) {
  (doc as unknown as { y: number }).y = y;
}

