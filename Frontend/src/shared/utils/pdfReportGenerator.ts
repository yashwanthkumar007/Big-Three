async function loadImageAsDataUrl(url: string): Promise<string> {
  const response = await fetch(url);
  const blob = await response.blob();
  return new Promise((resolve, reject) => {
    const reader = new FileReader();
    reader.onload = () => resolve(reader.result as string);
    reader.onerror = reject;
    reader.readAsDataURL(blob);
  });
}

/* ------------------------------------------------------------------ */
/* Invisible, hover-enabled tooltip annotations                       */
/*                                                                     */
/* jsPDF's built-in doc.createAnnotation({ type: "text" }) writes a   */
/* PDF /Subtype /Text annotation. Per the PDF spec (12.5.6.4), Text   */
/* annotations are REQUIRED to display an icon — there's no flag to   */
/* suppress it while keeping the annotation interactive. To get a     */
/* hover/click popup WITHOUT that icon, we write our own /Subtype     */
/* /Square annotation directly using jsPDF's internal write helpers   */
/* (the same primitives its own annotations plugin uses). A Square    */
/* annotation still carries /Contents + /Popup (so Acrobat/Reader     */
/* shows the reason on hover/click), but with no border colour and    */
/* zero border width it has no default appearance of its own — so     */
/* nothing renders except our existing red highlight rectangle.       */
/* ------------------------------------------------------------------ */

type TooltipAnnotationEntry = {
  x: number;
  y: number;
  w: number;
  h: number;
  contents: string;
};

type JsPdfInternalExt = {
  pdfEscape: (text: string) => string;
  write: (...args: Array<string | number>) => void;
  getCoordinateString: (value: number) => string;
  getVerticalCoordinateString: (value: number) => string;
  newAdditionalObject: () => { objId: number; content: string };
  getEncryptor: (objId: number) => (data: string) => string;
  getPageInfoByObjId: (objId: number) => { objId: number; pageNumber: number };
  getCurrentPageInfo: () => { objId: number; pageNumber: number };
  events: {
    subscribe: (
      topic: string,
      callback: (...args: unknown[]) => void,
      once?: boolean
    ) => string;
  };
};

function getInternal(doc: jsPDF): JsPdfInternalExt {
  return doc.internal as unknown as JsPdfInternalExt;
}

/**
 * Registers a one-time "putPage" hook on this document instance that
 * writes invisible, popup-enabled Square annotations for any tooltip
 * entries collected for that page. Safe to call multiple times — only
 * subscribes once per document.
 */
function ensureInvisibleTooltipSupport(
  doc: jsPDF
): Map<number, TooltipAnnotationEntry[]> {
  const withRegistration = doc as unknown as {
    __tooltipsByPage?: Map<number, TooltipAnnotationEntry[]>;
    __tooltipHandlerRegistered?: boolean;
  };

  if (withRegistration.__tooltipHandlerRegistered && withRegistration.__tooltipsByPage) {
    return withRegistration.__tooltipsByPage;
  }

  const tooltipsByPage = new Map<number, TooltipAnnotationEntry[]>();
  withRegistration.__tooltipsByPage = tooltipsByPage;
  withRegistration.__tooltipHandlerRegistered = true;

  const internal = getInternal(doc);

  internal.events.subscribe("putPage", function (
    this: jsPDF,
    ...args: unknown[]
  ) {
    const putPageData = args[0] as { objId: number; pageNumber: number };
    const entries = tooltipsByPage.get(putPageData.pageNumber);
    if (!entries || entries.length === 0) {
      return;
    }

    const pageInternal = getInternal(this);
    const pageInfo = pageInternal.getPageInfoByObjId(putPageData.objId);

    pageInternal.write("/Annots [");

    for (const entry of entries) {
      const objSquare = pageInternal.newAdditionalObject();
      const objPopup = pageInternal.newAdditionalObject();
      const encryptor = pageInternal.getEncryptor(objSquare.objId);

      const rect =
        "/Rect [" +
        pageInternal.getCoordinateString(entry.x) +
        " " +
        pageInternal.getVerticalCoordinateString(entry.y + entry.h) +
        " " +
        pageInternal.getCoordinateString(entry.x + entry.w) +
        " " +
        pageInternal.getVerticalCoordinateString(entry.y) +
        "] ";

      objSquare.content =
        "<</Type /Annot /Subtype /Square " +
        rect +
        "/Contents (" +
        pageInternal.pdfEscape(encryptor(entry.contents)) +
        ")" +
        " /C []" + // no border colour -> no visible box of its own
        " /BS <</W 0>>" + // zero border width -> no default appearance/icon
        " /Popup " +
        objPopup.objId +
        " 0 R" +
        " /P " +
        pageInfo.objId +
        " 0 R" +
        " /T (" +
        pageInternal.pdfEscape(encryptor("Reason")) +
        ") >>";

      objPopup.content =
        "<</Type /Annot /Subtype /Popup " +
        rect +
        " /Parent " +
        objSquare.objId +
        " 0 R >>";

      pageInternal.write(objSquare.objId, "0 R", objPopup.objId, "0 R");
    }

    pageInternal.write("]");
  });

  return tooltipsByPage;
}

/**
 * Adds an invisible, hover/click-enabled tooltip over the given region
 * of the CURRENT page. Must be called before doc.addPage() moves past
 * that page, since it reads the current page number at call time.
 */
function addTooltipAnnotation(
  doc: jsPDF,
  x: number,
  y: number,
  w: number,
  h: number,
  text: string
) {
  try {
    const tooltipsByPage = ensureInvisibleTooltipSupport(doc);
    const pageNumber = getInternal(doc).getCurrentPageInfo().pageNumber;

    if (!tooltipsByPage.has(pageNumber)) {
      tooltipsByPage.set(pageNumber, []);
    }

    tooltipsByPage.get(pageNumber)!.push({ x, y, w, h, contents: text });
  } catch (error) {
    console.error("[PDF REPORT] Failed to add annotation:", error);
  }
}

async function drawSampleImageWithOverlays(
  doc: jsPDF,
  result: InspectionResult,
  commentSelections: Record<number, string>
) {
  const pages = result.pages ?? [];

  for (const page of pages) {
    if (!page.sampleImage) {
      continue;
    }

    // Get differences for this page
    const pageDifferences = result.differences.filter(
      (d) => (d.page ?? 0) === page.page
    );

    if (pageDifferences.length === 0) {
      continue;
    }

    // Add a new page for the sample image
    doc.addPage();
    setY(doc, MARGIN + 8);

    // Section title
    addSectionTitle(doc, `Sample File - Page ${page.page + 1}`);

    // Load the image
    try {
      const imageDataUrl = await loadImageAsDataUrl(page.sampleImage);

      // Calculate image dimensions to fit within the page
      const maxWidth = PAGE_WIDTH - MARGIN * 2;
      const maxHeight = PAGE_HEIGHT - 40;

      const imgWidth = page.sampleWidth ?? 0;
      const imgHeight = page.sampleHeight ?? 0;

      if (imgWidth <= 0 || imgHeight <= 0) {
        continue;
      }

      const scale = Math.min(maxWidth / imgWidth, maxHeight / imgHeight);
      const drawWidth = imgWidth * scale;
      const drawHeight = imgHeight * scale;

      const imgX = MARGIN;
      const imgY = getY(doc);

      // Draw the image
      doc.addImage(
        imageDataUrl,
        "PNG",
        imgX,
        imgY,
        drawWidth,
        drawHeight
      );

      // Draw red boxes and diff numbers for each difference
      for (const diff of pageDifferences) {
        if (!diff.sampleBox) {
          continue;
        }

        const box = diff.sampleBox;
        const boxX = imgX + box.x * scale;
        const boxY = imgY + box.y * scale;
        const boxW = Math.max(box.width * scale, 2);
        const boxH = Math.max(box.height * scale, 2);

        // Red border — the visible marker on the image
        doc.setDrawColor(RED_HIGHLIGHT[0], RED_HIGHLIGHT[1], RED_HIGHLIGHT[2]);
        doc.setLineWidth(0.5);
        doc.rect(boxX, boxY, boxW, boxH, "S");

        // Diff number badge
        const badgeSize = 5;
        const badgeX = boxX;
        const badgeY = boxY - badgeSize;

        // Badge background
        doc.setFillColor(RED_HIGHLIGHT[0], RED_HIGHLIGHT[1], RED_HIGHLIGHT[2]);
        doc.circle(badgeX + badgeSize / 2, badgeY + badgeSize / 2, badgeSize / 2, "F");

        // Badge text
        doc.setFont("helvetica", "bold");
        doc.setFontSize(6);
        doc.setTextColor(WHITE[0], WHITE[1], WHITE[2]);
        doc.text(
          String(diff.id),
          badgeX + badgeSize / 2,
          badgeY + badgeSize / 2 + 1,
          { align: "center" }
        );

        // Invisible hover/click tooltip covering the same box — shows
        // the reason for the difference in compatible PDF viewers,
        // with no separate icon rendered anywhere.
        const reason = commentSelections[diff.id] ?? diff.comment ?? diff.type;
        if (reason) {
          addTooltipAnnotation(doc, boxX, boxY, boxW, boxH, reason);
        }
      }

      setY(doc, imgY + drawHeight + 6);
    } catch (error) {
      console.error("[PDF REPORT] Failed to draw sample image:", error);
    }
  }
}

