export type PdfReportOptions = {
  sessionId: string;
  result: InspectionResult;
  commentSelections: Record<number, string>;
  levelSelections?: Record<number, string>;
  differenceFilters: DifferenceFilters;
};

export async function generateInspectionPdf({
  sessionId,
  result,
  commentSelections,
  levelSelections = {},
  differenceFilters,
}: PdfReportOptions): Promise<jsPDF> {
  console.log("[PDF REPORT] Starting PDF generation");
  console.log("[PDF REPORT] Inspection report:", result);
  console.log("[PDF REPORT] Total differences:", result.totalDifferences);

  const doc = new jsPDF({
    orientation: "portrait",
    unit: "mm",
    format: "a4",
  });

  setY(doc, MARGIN + 8);

  /* ---------------------------------------------------------------
   * REPORT HEADER
   * ------------------------------------------------------------- */

  // Title band
  doc.setFillColor(BRAND_PRIMARY[0], BRAND_PRIMARY[1], BRAND_PRIMARY[2]);
  doc.rect(0, 0, PAGE_WIDTH, 30, "F");

  doc.setFont("helvetica", "bold");
  doc.setFontSize(16);
  doc.setTextColor(WHITE[0], WHITE[1], WHITE[2]);
  doc.text("Text Inspection Report", MARGIN, 14);

  doc.setFont("helvetica", "normal");
  doc.setFontSize(9);
  doc.setTextColor(220, 220, 235);
  doc.text(`Session ID: ${sessionId}`, MARGIN, 22);

  const now = new Date();
  const dateStr = now.toLocaleString();
  doc.text(`Date: ${dateStr}`, MARGIN, 27);

  // File names
  setY(doc, 36);
  doc.setFont("helvetica", "bold");
  doc.setFontSize(10);
  doc.setTextColor(BRAND_PRIMARY[0], BRAND_PRIMARY[1], BRAND_PRIMARY[2]);
  doc.text("Files", MARGIN, getY(doc) + 4);
  setY(doc, getY(doc) + 7);

  doc.setFont("helvetica", "normal");
  doc.setFontSize(9);
  doc.setTextColor(TEXT_COLOR[0], TEXT_COLOR[1], TEXT_COLOR[2]);

  const masterFileName = result.masterFileName;
  const sampleFileName = result.sampleFileName;

  const fileLines = doc.splitTextToSize(
    `Master: ${masterFileName}`,
    PAGE_WIDTH - MARGIN * 2
  );
  doc.text(fileLines, MARGIN, getY(doc));
  setY(doc, getY(doc) + fileLines.length * 3.5 + 2);

  const sampleLines = doc.splitTextToSize(
    `Sample: ${sampleFileName}`,
    PAGE_WIDTH - MARGIN * 2
  );
  doc.text(sampleLines, MARGIN, getY(doc));
  setY(doc, getY(doc) + sampleLines.length * 3.5 + 4);

  /* ---------------------------------------------------------------
   * SUMMARY SECTION
   * ------------------------------------------------------------- */

  addSectionTitle(doc, "Inspection Summary");

  const differences = result.differences;

  // Count by type
  const countByType = (type: string) =>
    differences.filter((d) => d.type === type).length;

  const summaryRows: SummaryRow[] = [
    { label: "Case", count: countByType("Case") },
    { label: "Change", count: countByType("Change") },
    { label: "Deletion", count: countByType("Deletion") },
    { label: "Hyphen", count: countByType("Hyphen") },
    { label: "Line Break (Space)", count: countByType("Line Break") },
    { label: "Location", count: countByType("Location") },
    { label: "Space", count: countByType("Space") },
    { label: "Bold", count: countByType("Bold") },
    { label: "Color", count: countByType("Color") },
    { label: "Fonts (Mixed)", count: countByType("Font Type") },
    { label: "Italic", count: countByType("Italic") },
    { label: "Size", count: countByType("Size") },
    { label: "Sub/Super", count: countByType("Sub/Super") },
    { label: "Insertion", count: countByType("Insertion") },
    { label: "Font Type", count: countByType("Font Type") },
    { label: "Underline", count: countByType("Underline") },
    { label: "Min Font Size", count: countByType("Min Font Size") },
  ];

  // Total differences line
  doc.setFont("helvetica", "bold");
  doc.setFontSize(10);
  doc.setTextColor(TEXT_COLOR[0], TEXT_COLOR[1], TEXT_COLOR[2]);
  doc.text(`Total Differences: ${differences.length}`, MARGIN, getY(doc) + 4);
  setY(doc, getY(doc) + 8);

  drawSummaryTable(doc, summaryRows, differences.length);

  /* ---------------------------------------------------------------
   * DIFFERENCES TABLE
   * ------------------------------------------------------------- */

  addSectionTitle(doc, "Differences");

  const tableBody = differences.map((d) => {
    const status = commentSelections[d.id] ?? "None";
    const level = levelSelections[d.id] ?? d.level ?? "None";
    return [
      String(d.id),
      d.type || "—",
      d.master || "—",
      d.sample || "—",
      String(d.page ?? 1),
      level,
      status,
    ];
  });

  autoTable(doc, {
    startY: getY(doc) + 2,
    head: [["ID", "Type", "Master", "Sample", "Page", "Level", "Comment"]],
    body: tableBody,
    theme: "striped",
    styles: {
      fontSize: 8,
      cellPadding: 2,
      textColor: TEXT_COLOR,
      overflow: "linebreak",
      valign: "top",
    },
    headStyles: {
      fillColor: BRAND_PRIMARY,
      textColor: WHITE,
      fontStyle: "bold",
      fontSize: 8,
    },
    alternateRowStyles: {
      fillColor: LIGHT_BG,
    },
    columnStyles: {
      0: { cellWidth: 10 },
      1: { cellWidth: 20 },
      2: { cellWidth: 46 },
      3: { cellWidth: 46 },
      4: { cellWidth: 12 },
      5: { cellWidth: 20 },
      6: { cellWidth: 36 },
    },
    margin: { left: MARGIN, right: MARGIN },
  });

  setY(doc, (doc as unknown as { lastAutoTable: { finalY: number } }).lastAutoTable.finalY + 8);

  /* ---------------------------------------------------------------
   * SAMPLE FILE WITH DIFFERENCE OVERLAYS
   * ------------------------------------------------------------- */

  await drawSampleImageWithOverlays(doc, result, commentSelections);

  /* ---------------------------------------------------------------
   * REPORT PARAMETERS (LAST PAGE)
   * ------------------------------------------------------------- */

  drawReportParameters(doc, differenceFilters);

  /* ---------------------------------------------------------------
   * PAGE HEADERS / FOOTERS
   * ------------------------------------------------------------- */

  addPageHeaderAndFooter(doc, "Text Inspection Report", sessionId);

  console.log("[PDF REPORT] PDF generation completed");

  return doc;
}

/**
 * Generates the inspection report PDF and returns it as a Blob.
 * Used by both the Download PDF Report and Share Report flows so
 * the exact same PDF content is used in both.
 */
export async function generateInspectionReportPdfBlob(
  options: PdfReportOptions
): Promise<Blob> {
  const doc = await generateInspectionPdf(options);
  return doc.output("blob");
}

export async function downloadInspectionPdf({
  sessionId,
  result,
  commentSelections,
  levelSelections = {},
  differenceFilters,
}: PdfReportOptions) {
  if (!result || result.differences.length === 0) {
    console.error("[PDF REPORT] No inspection results available.");
    alert("No inspection results available to generate a PDF report.");
    return;
  }

  try {
    console.log("[PDF REPORT] Starting PDF generation");
    const blob = await generateInspectionReportPdfBlob({
      sessionId,
      result,
      commentSelections,
      levelSelections,
      differenceFilters,
    });
    const fileName = `inspection-report-${sessionId}.pdf`;
    console.log("[PDF REPORT] Saving PDF as:", fileName);

    // Trigger browser download from the Blob
    const url = URL.createObjectURL(blob);
    const link = document.createElement("a");
    link.href = url;
    link.download = fileName;
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
    URL.revokeObjectURL(url);

    console.log("[PDF REPORT] PDF generation completed");
  } catch (error) {
    console.error("[PDF REPORT] PDF generation failed:", error);
    alert(
      "Failed to generate the PDF report. Please check the console for details."
    );
  }
}
