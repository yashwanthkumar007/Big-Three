/* Summary table rendering                                            */
/* ------------------------------------------------------------------ */

type SummaryRow = {
  label: string;
  count: number;
};

function drawSummaryTable(
  doc: jsPDF,
  rows: SummaryRow[],
  totalDifferences: number
) {
  const colWidth = (PAGE_WIDTH - MARGIN * 2) / 4;
  const rowHeight = 8;
  const cellPadding = 2;

  let x = MARGIN;
  let y = getY(doc);

  rows.forEach((row, index) => {
    // Draw cell background
    doc.setFillColor(LIGHT_BG[0], LIGHT_BG[1], LIGHT_BG[2]);
    doc.rect(x, y, colWidth, rowHeight, "F");

    // Draw cell border
    doc.setDrawColor(200, 205, 210);
    doc.rect(x, y, colWidth, rowHeight, "S");

    // Label
    doc.setFont("helvetica", "normal");
    doc.setFontSize(8);
    doc.setTextColor(TEXT_COLOR[0], TEXT_COLOR[1], TEXT_COLOR[2]);
    doc.text(row.label, x + cellPadding, y + rowHeight / 2 + 1);

    // Count (right-aligned)
    doc.setFont("helvetica", "bold");
    doc.setFontSize(9);
    doc.setTextColor(BRAND_PRIMARY[0], BRAND_PRIMARY[1], BRAND_PRIMARY[2]);
    doc.text(
      String(row.count),
      x + colWidth - cellPadding,
      y + rowHeight / 2 + 1,
      { align: "right" }
    );

    // Move to next column
    x += colWidth;

    // New row after 4 columns
    if ((index + 1) % 4 === 0) {
      x = MARGIN;
      y += rowHeight;
    }
  });

  // If not a multiple of 4, advance to next row
  if (rows.length % 4 !== 0) {
    y += rowHeight;
  }

  // Total row
  doc.setFillColor(BRAND_PRIMARY[0], BRAND_PRIMARY[1], BRAND_PRIMARY[2]);
  doc.rect(MARGIN, y, PAGE_WIDTH - MARGIN * 2, rowHeight, "F");

  doc.setFont("helvetica", "bold");
  doc.setFontSize(9);
  doc.setTextColor(WHITE[0], WHITE[1], WHITE[2]);
  doc.text("Included", MARGIN + cellPadding, y + rowHeight / 2 + 1);
  doc.text(
    String(totalDifferences),
    PAGE_WIDTH - MARGIN - cellPadding,
    y + rowHeight / 2 + 1,
    { align: "right" }
  );

  setY(doc, y + rowHeight + 4);
}

