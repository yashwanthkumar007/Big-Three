function drawReportParameters(
  doc: jsPDF,
  differenceFilters: DifferenceFilters
) {
  doc.addPage();
  setY(doc, MARGIN + 8);

  addSectionTitle(doc, "Text Inspection Profile: Default");

  /* ---------------------------------------------------------------
   * DIFFERENCE FILTERS SELECTED
   * ------------------------------------------------------------- */

  addSectionTitle(doc, "Difference Filters Selected");

  const filterRows: Array<[string, boolean]> = [
    ["Case", differenceFilters.case],
    ["Change", differenceFilters.change],
    ["Deletion", differenceFilters.deletion],
    ["Hyphen", differenceFilters.hyphen],
    ["Insertion", differenceFilters.insertion],
    ["Location", differenceFilters.location],
    ["Bold", differenceFilters.bold],
    ["Color", differenceFilters.color],
    ["Font Type", differenceFilters.fontType],
    ["Space", differenceFilters.space],
    ["Size", differenceFilters.size],
    ["Underline", differenceFilters.underline],
  ];

  const colWidth = (PAGE_WIDTH - MARGIN * 2) / 3;
  const rowHeight = 7;
  const cellPadding = 2;

  let x = MARGIN;
  let y = getY(doc);

  filterRows.forEach(([label, enabled], index) => {
    // Draw cell background
    doc.setFillColor(LIGHT_BG[0], LIGHT_BG[1], LIGHT_BG[2]);
    doc.rect(x, y, colWidth, rowHeight, "F");

    // Draw cell border
    doc.setDrawColor(200, 205, 210);
    doc.rect(x, y, colWidth, rowHeight, "S");

    // Label
    doc.setFont("helvetica", "normal");
    doc.setFontSize(8);
    doc.setTextColor(TEXT_COLOR[0], TEXT_COLOR[1], TEXT_COLOR[2]);
    doc.text(label, x + cellPadding, y + rowHeight / 2 + 1);

    // Value (Yes/No)
    doc.setFont("helvetica", "bold");
    doc.setFontSize(8);
    const valueColor = enabled ? [46, 125, 50] : [198, 40, 40];
    doc.setTextColor(valueColor[0], valueColor[1], valueColor[2]);
    doc.text(
      enabled ? "Yes" : "No",
      x + colWidth - cellPadding,
      y + rowHeight / 2 + 1,
      { align: "right" }
    );

    // Move to next column
    x += colWidth;

    // New row after 3 columns
    if ((index + 1) % 3 === 0) {
      x = MARGIN;
      y += rowHeight;
    }
  });

  // If not a multiple of 3, advance to next row
  if (filterRows.length % 3 !== 0) {
    y += rowHeight;
  }

  setY(doc, y + 6);

  /* ---------------------------------------------------------------
   * INSPECTION REPORT PARAMETERS
   * ------------------------------------------------------------- */

  addSectionTitle(doc, "Inspection Report Parameters");

  const paramRows: Array<[string, string]> = [
    ["Min Font Size", "Unknown"],
    ["Template Mode", "None"],
    ["Language", "Default"],
    ["Image Compare", "Disabled"],
    ["Barcode Detection", "Disabled"],
    ["Braille Detection", "Disabled"],
    ["OverPrint", "Enabled"],
    ["Invisible Text", "Disabled"],
    ["Line Processing", "Underlines + Tables"],
    ["Master Selected Pages", "All pages"],
    ["Sample Selected Pages", "All pages"],
    ["Remove Headers/Footers", "Enabled"],
  ];

  const paramColWidth = (PAGE_WIDTH - MARGIN * 2) / 2;
  const paramRowHeight = 7;

  x = MARGIN;
  y = getY(doc);

  paramRows.forEach(([label, value], index) => {
    // Draw cell background
    doc.setFillColor(LIGHT_BG[0], LIGHT_BG[1], LIGHT_BG[2]);
    doc.rect(x, y, paramColWidth, paramRowHeight, "F");

    // Draw cell border
    doc.setDrawColor(200, 205, 210);
    doc.rect(x, y, paramColWidth, paramRowHeight, "S");

    // Label
    doc.setFont("helvetica", "normal");
    doc.setFontSize(8);
    doc.setTextColor(TEXT_COLOR[0], TEXT_COLOR[1], TEXT_COLOR[2]);
    doc.text(label, x + cellPadding, y + paramRowHeight / 2 + 1);

    // Value
    doc.setFont("helvetica", "bold");
    doc.setFontSize(8);
    doc.setTextColor(BRAND_PRIMARY[0], BRAND_PRIMARY[1], BRAND_PRIMARY[2]);
    doc.text(
      value,
      x + paramColWidth - cellPadding,
      y + paramRowHeight / 2 + 1,
      { align: "right" }
    );

    // Move to next column
    x += paramColWidth;

    // New row after 2 columns
    if ((index + 1) % 2 === 0) {
      x = MARGIN;
      y += paramRowHeight;
    }
  });

  // If not a multiple of 2, advance to next row
  if (paramRows.length % 2 !== 0) {
    y += paramRowHeight;
  }

  setY(doc, y + 4);
}

