const BRAND_PRIMARY: [number, number, number] = [42, 39, 110]; // #2A276E
const RED_HIGHLIGHT: [number, number, number] = [229, 115, 115]; // #e57373
const LIGHT_BG: [number, number, number] = [243, 245, 247]; // #f3f5f7
const TEXT_COLOR: [number, number, number] = [62, 66, 74]; // #3f4250
const WHITE: [number, number, number] = [255, 255, 255];

